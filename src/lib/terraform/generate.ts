import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import type { Guest, PveNode } from "@prisma/client";

import { env, paths } from "../env";

/**
 * Workspace generation.
 *
 * Every guest gets its own directory with its own state file. That isolation is
 * the point: a container whose apply is wedged cannot block anyone else's
 * order, and destroying it is a self-contained `terraform destroy` rather than
 * a surgical edit of a shared configuration.
 *
 * The generated `main.tf` is fixed per guest kind and never contains a value —
 * everything variable lives in `terraform.tfvars.json`, so a resize is a file
 * rewrite plus an apply, with no HCL templating to get wrong. Credentials are
 * not written to disk at all; the worker injects them as TF_VAR_* at spawn
 * time.
 */

/** Absolute path to the vendored modules, resolved from the app root. */
export function modulesDir(): string {
  return (
    process.env.PORTAL_MODULES_DIR ?? path.join(process.cwd(), "terraform", "modules")
  );
}

const PROVIDER_TF = `# Generated by the Proxmox portal. Do not edit by hand.

terraform {
  required_version = ">= 1.6"

  required_providers {
    proxmox = {
      source  = "bpg/proxmox"
      version = "~> 0.111"
    }
  }
}

variable "pve_endpoint" { type = string }
variable "pve_api_token" {
  type      = string
  sensitive = true
}
variable "pve_insecure" {
  type    = bool
  default = true
}
variable "pve_ssh_username" {
  type    = string
  default = "root"
}
variable "pve_ssh_private_key" { type = string }
variable "pve_node_addresses" {
  type    = map(string)
  default = {}
}

provider "proxmox" {
  endpoint  = var.pve_endpoint
  api_token = var.pve_api_token
  insecure  = var.pve_insecure

  ssh {
    agent       = false
    username    = var.pve_ssh_username
    private_key = file(var.pve_ssh_private_key)

    # The cluster is quorate over WireGuard, so the address the API reports for
    # a node is not always reachable from here. Pin them.
    dynamic "node" {
      for_each = var.pve_node_addresses
      content {
        name    = node.key
        address = node.value
      }
    }
  }
}
`;

