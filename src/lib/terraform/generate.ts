/** The non-secret half of a workspace's inputs. */
export function tfvarsFor(
  guest: Guest,
  node: PveNode,
): Record<string, unknown> {
  const dns = node.dnsServers
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);

  const common = {
    hostname: guest.hostname,
    node_name: node.name,
    vm_id: guest.vmid,
    cores: guest.cores,
    memory: guest.memoryMb,
    disk_size: guest.diskGb,
    // The guest's own datastore, not the node's default. After a migration the
    // disk sits wherever PVE put it; handing Terraform the target node's
    // preferred storage instead would read as a storage change and force a
    // replacement, destroying the disk to "fix" it.
    datastore_id: guest.datastore || node.defaultDatastore,
    bridge: guest.bridge,
    mtu: guest.mtu,
    ipv4_address: guest.ipv4Address,
    ipv4_gateway: guest.ipv4Gateway,
    dns_servers: dns,
    ssh_public_keys: guest.sshPublicKey ? [guest.sshPublicKey.trim()] : [],
    description: `${guest.hostname} — ordered through the portal. Managed by Terraform.`,
    tags: ["terraform", "portal", guest.kind.toLowerCase()],
  };

  if (guest.kind === "LXC") {
    return {
      ...common,
      swap: guest.swapMb,
      template_file_id: guest.templateFileId,
      os_type: guest.osType,
    };
  }

  // Exactly one source reaches the module: an ISO install, a clone, or a
  // cloud image import.
  return {
    ...common,
    ci_user: guest.ciUser,
    cloud_image_file_id:
      guest.isoFileId || guest.cloneVmId ? null : guest.templateFileId,
    clone_vm_id: guest.isoFileId ? null : guest.cloneVmId,
    iso_file_id: guest.isoFileId,
  };
}

/**
 * Write (or rewrite) a guest's workspace. Safe to call repeatedly — a resize or
 * a migration is exactly this function plus another apply.
 */
export async function writeWorkspace(
  guest: Guest,
  node: PveNode,
): Promise<string> {
  const dir = paths.workspace(guest.id);
  await mkdir(dir, { recursive: true });

  const modules = modulesDir();
  await writeFile(path.join(dir, "provider.tf"), PROVIDER_TF, "utf8");
  await writeFile(
    path.join(dir, "main.tf"),
    guest.kind === "LXC" ? lxcMainTf(modules) : vmMainTf(modules),
    "utf8",
  );
  await writeFile(
    path.join(dir, "terraform.tfvars.json"),
    `${JSON.stringify(tfvarsFor(guest, node), null, 2)}\n`,
    "utf8",
  );

  return dir;
}

export async function ensureRuntimeDirs(): Promise<void> {
  await mkdir(paths.workspaces(), { recursive: true });
  await mkdir(paths.logs(), { recursive: true });
  await mkdir(env.pluginCacheDir, { recursive: true });
}
